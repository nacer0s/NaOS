#!/usr/bin/env python3
"""NaOS tools/font_render.py — rasterize an installed monospace TTF into a
C bitmap header for the kernel console. Written for NaOS (the font DATA
comes from the installed package; this converter is ours).

Output layout matches the kernel blit cache: 2 bits of coverage alpha per
pixel, MSB-first, rows of ceil(cell_w/4) bytes.
"""
import argparse
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print("ERROR: Pillow is required (pacman -S mingw-w64-ucrt-x86_64-python-pillow)",
          file=sys.stderr)
    sys.exit(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--size", type=int, required=True, help="pixel size")
    ap.add_argument("--cell-w", type=int, required=True)
    ap.add_argument("--cell-h", type=int, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--tag", default="",
                    help="variant tag: empty keeps kFontBits/FONT_CELL_W "
                         "(default bitmap); e.g. 'small' emits "
                         "kFontSmallBits/FONT_SMALL_W")
    a = ap.parse_args()

    font = ImageFont.truetype(a.ttf, a.size)
    ascent, descent = font.getmetrics()
    total = ascent + descent
    if total > a.cell_h:
        print(f"ERROR: glyphs {total}px tall do not fit {a.cell_h}px cells "
              f"(size {a.size} too big)", file=sys.stderr)
        sys.exit(1)
    baseline = (a.cell_h - total) // 2 + ascent

    # Widest advance must fit the cell.
    try:
        adv = max(font.getlength(chr(c)) for c in range(32, 127))
    except AttributeError:  # very old Pillow: getsize fallback
        adv = max(font.getsize(chr(c))[0] for c in range(32, 127))
    if adv > a.cell_w + 0.5:
        print(f"WARNING: max advance {adv:.1f}px exceeds cell {a.cell_w}px; "
              f"glyphs will clip", file=sys.stderr)

    glyphs = {}
    for c in range(128):
        img = Image.new("L", (a.cell_w, a.cell_h), 0)
        if 32 <= c < 127:
            d = ImageDraw.Draw(img)
            d.text((0, baseline), chr(c), font=font, anchor="ls", fill=255)
        glyphs[c] = img

    bpr = (a.cell_w + 3) // 4  # bytes per row (2 bits/px)
    if a.tag:
        t = a.tag.upper()
        guard = f"NAOS_FONT_{t}_H"
        cw, chh = f"FONT_{t}_W", f"FONT_{t}_H"
        sym = f"kFont{a.tag.capitalize()}Bits"
    else:  # default bitmap: historic names, byte-identical output
        guard, cw, chh = "NAOS_FONT_BITMAP_H", "FONT_CELL_W", "FONT_CELL_H"
        sym = "kFontBits"
    with open(a.out, "w") as f:
        f.write("/* Generated by NaOS tools/font_render.py — do not edit.\n")
        f.write(f" * Source: {os.path.basename(a.ttf)} size {a.size}, "
                f"cell {a.cell_w}x{a.cell_h}, 2-bit coverage alpha. */\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define {cw} {a.cell_w}\n")
        f.write(f"#define {chh} {a.cell_h}\n\n")
        f.write(f"static const uint8_t {sym}[128][{a.cell_h}][{bpr}] = {{\n")
        for c in range(128):
            px = glyphs[c].load()
            f.write(f"  /* {c:#04x} {chr(c) if 32 <= c < 127 else ' '} */\n  {{")
            for y in range(a.cell_h):
                f.write("{")
                for b in range(bpr):
                    v = 0
                    for k in range(4):
                        x = b * 4 + k
                        if x < a.cell_w:
                            q = (px[x, y] * 4) >> 8
                            if q > 3:
                                q = 3
                            v |= q << (6 - k * 2)
                    f.write(f"0x{v:02x},")
                f.write("},")
            f.write("},\n")
        f.write(f"}};\n\n#endif /* {guard} */\n")
    print(f"font: {a.ttf} size={a.size} cell={a.cell_w}x{a.cell_h} "
          f"advance~{adv:.1f} -> {a.out}")


if __name__ == "__main__":
    main()
